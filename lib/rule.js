/*
 *  Majinng.rule
 */
"use strict";

module.exports = function(param = {}) {

    const n = param['人数'] ?? 4;
    if (n !== 3 && n !== 4) throw new RangeError('人数は3または4です');
    if (n === 3 && param['役満パオあり'] === true)
        throw new Error('三人戦の役満パオは未対応です');

    const starts  = n === 3 ? 35000 : 25000;
    const returns = n === 3 ? 40000 : 30000;
    const noten   = n === 3 ? 2000  : 3000;
    const uma     = n === 3 ? ['20.0','0.0','-20.0']
                            : ['20.0','10.0','-10.0','-20.0'];

    let rule = {
        /* 人数 */
        '人数': n,

        /* 点数関連 */
        '配給原点': starts,
        '返し点':   returns,
        '順位点':   uma,
        'ノーテン罰点': noten,
        '本場支払点':   100,
        '連風牌は2符': false,
        '固定符':   null,
            // null: 通常の符計算, 数値: 符を固定値として点数を決める(翻数固定表用)

        /* 赤牌有無/クイタンなど */
        '赤牌':         n === 3 ? { m: 0, p: 1, s: 1 }
                                : { m: 1, p: 1, s: 1 },
        'クイタンあり': true,
        '喰い替え許可レベル': 0,
            // 0: 喰い替えなし, 1: スジ喰い替えあり,  2: 現物喰い替えもあり

        /* 局数関連 */
        '場数':             2,
            // 0: 一局戦, 1: 東風戦, 2： 東南戦, 4: 一荘戦
        '途中流局あり':     true,
        '流し満貫あり':     true,
        'ノーテン宣言あり': false,
        'ノーテン罰あり':   true,
        '最大同時和了数': 2,
            // 1: 頭ハネ, 2: ダブロンあり, 3: トリロンあり
        '連荘方式':         2,
            // 0: 連荘なし, 1: 和了連荘, 2: テンパイ連荘, 3: ノーテン連荘
        'トビ終了あり':     true,
        'オーラス止めあり': true,
        '延長戦方式':       1,
            // 0: 延長戦なし, 1: サドンデス, 2: 連荘優先サドンデス, 3: 4局固定

        /* リーチ/ドラ関連 */
        '一発あり':         true,
        '裏ドラあり':       true,
        'カンドラあり':     true,
        'カン裏あり':       true,
        'カンドラ後乗せ':   true,
        'ツモ番なしリーチあり':   false,
        'リーチ後暗槓許可レベル': 2,
            // 0: 暗槓不可, 1: 牌姿の変わる暗槓不可, 2： 待ちの変わる暗槓不可

        /* 役満関連 */
        '役満の複合あり':   true,
        'ダブル役満あり':   true,
        '数え役満あり':     true,
        '役満パオあり':     n !== 3,
        '切り上げ満貫あり': false,
    };

    for (let key of Object.keys(param)) {
        rule[key] = param[key];
    }

    /* 検証済みの人数・不許可の組合せをマージ結果で上書きさせない */
    rule['人数'] = n;
    if (n === 3 && rule['役満パオあり'])
        throw new Error('三人戦の役満パオは未対応です');

    if (! Array.isArray(rule['順位点']) || rule['順位点'].length !== n)
        throw new Error('順位点の要素数は人数と一致しなければなりません');

    if (n === 3 && (! rule['赤牌'] || (rule['赤牌'].m ?? 0) !== 0))
        throw new Error('三人戦に赤萬子は使えません');

    if (rule['本場支払点'] !== 100)
        throw new Error('本場支払点は100以外未対応です');

    return rule;
}
